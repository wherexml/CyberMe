import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {build} from 'esbuild';

const root=fileURLToPath(new URL('../',import.meta.url));
const out=resolve(root,'mock/opstwins/vendor');
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const upstream=JSON.parse(await readFile(resolve(root,'vendor/mock-upstream-manifest.json'),'utf8'));
for(const file of upstream.files){
  if(sha(await readFile(resolve(root,file.localPath)))!==file.sha256)throw Error('Upstream source changed: '+file.localPath);
}
// Extract this pure helper verbatim; do not pull Gmail/Prisma/filebot into browser.
const source=await readFile(resolve(root,'vendor/inbox-zero/upstream/apps/web/utils/reply-tracker/thread-status-context.ts'),'utf8');
const constants=source.slice(source.indexOf('const THREAD_STATUS_FIRST_MESSAGE_MAX_LENGTH'),source.indexOf('// The filing assistant'));
const fn=source.slice(source.indexOf('function getMaxLengthForThreadStatusMessage('));
if(!constants||!fn.startsWith('function getMaxLengthForThreadStatusMessage('))throw Error('Pinned thread helper not found');
await writeFile(resolve(root,'vendor/inbox-zero/thread-budget.ts'),'// Extracted verbatim from pinned thread-status-context.ts; see LICENSE.\n'+constants+'\nexport '+fn);
await mkdir(out,{recursive:true});
const entries=[['remend',resolve(root,'vendor/remend/src/index.ts')],['inbox-zero',resolve(root,'vendor/inbox-zero/browser-entry.ts')],['marked',resolve(root,'node_modules/marked/lib/marked.esm.js')]];
for(const [name,entry] of entries){
  await build({entryPoints:[entry],outfile:resolve(out,name+'.js'),bundle:true,format:'esm',platform:'browser',target:'es2023',minify:false,legalComments:'inline',
    alias:{'@/generated/prisma/enums':resolve(root,'vendor/inbox-zero/mock-enums.ts')},
    banner:{js:'// Generated by scripts/opstwins-mock-vendor.mjs; licenses and provenance in this directory.'}});
}
for(const [source,name] of [['vendor/remend/LICENSE','remend-LICENSE.txt'],['vendor/inbox-zero/LICENSE','inbox-zero-LICENSE.txt'],['node_modules/marked/LICENSE','marked-LICENSE.txt']])await copyFile(resolve(root,source),resolve(out,name));
const marked=JSON.parse(await readFile(resolve(root,'node_modules/marked/package.json'),'utf8'));
const remend=JSON.parse(await readFile(resolve(root,'vendor/remend/package.json'),'utf8'));
const esbuild=JSON.parse(await readFile(resolve(root,'node_modules/esbuild/package.json'),'utf8'));
const buildInputs={};for(const file of ['vendor/inbox-zero/browser-entry.ts','vendor/inbox-zero/mock-enums.ts','vendor/inbox-zero/thread-budget.ts','scripts/opstwins-mock-vendor.mjs','package-lock.json'])buildInputs[file]=sha(await readFile(resolve(root,file)));
const files={};for(const name of ['remend.js','inbox-zero.js','marked.js','remend-LICENSE.txt','inbox-zero-LICENSE.txt','marked-LICENSE.txt'])files[name]=sha(await readFile(resolve(out,name)));
await writeFile(resolve(out,'manifest.json'),JSON.stringify({scope:'local Mock evaluation; no production integration',remendVersion:remend.version,markedVersion:marked.version,esbuildVersion:esbuild.version,buildInputs,upstream,files},null,2)+'\n');
console.log(JSON.stringify({out,remend:remend.version,marked:marked.version,files:Object.keys(files).length}));
