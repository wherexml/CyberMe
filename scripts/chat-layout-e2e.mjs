// Run: EGO_TASK_SPACE=76 ego-browser nodejs < scripts/chat-layout-e2e.mjs
const fs=await import('node:fs/promises');
const task=await taskSpace(Number(process.env.EGO_TASK_SPACE||76));
const page=task.page('p1');
const out='/Users/steve/Projects/opstwin-advance/output/chat-layout-20261003';
await fs.mkdir(out,{recursive:true});
const checks=[];
function check(name,ok,details){checks.push({name,status:ok?'PASS':'FAIL',details});if(!ok)throw new Error(name+': '+JSON.stringify(details));}
await page.cdp('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});await page.cdp('Emulation.setTouchEmulationEnabled',{enabled:false});
await page.goto('http://127.0.0.1:46100/chat');
await page.click('.twin-entry');
await page.hover('.floating-header');
const measure=()=>{
 const root=document.querySelector('.floating-twin');const thread=root.querySelector('.conversation');
 const rect=e=>e.getBoundingClientRect();const rows=[...thread.querySelectorAll(':scope > [data-message-id]')];
 const users=rows.filter(e=>e.classList.contains('user-bubble'));
 const last=root.querySelector('.assistant-row:last-of-type');
 const actions=[...root.querySelectorAll('.message-actions')];
 const textarea=root.querySelector('textarea');
 return {rightAligned:users.every(e=>Math.abs(rect(e).right-rect(thread).right)<1),gaps:rows.slice(1).map((e,i)=>rect(e).top-rect(rows[i]).bottom),opacities:actions.map(e=>getComputedStyle(e).opacity),suggestions:root.querySelectorAll('.float-suggestions').length,placeholder:getComputedStyle(textarea,'::placeholder').fontSize,input:getComputedStyle(textarea).fontSize,overflow:root.scrollWidth>root.clientWidth,copyAlignment:[...root.querySelectorAll('.assistant-content')].filter(e=>e.querySelector('.message-action')).map(e=>rect(e.querySelector('.message-action svg')).left-rect(e.querySelector('.markdown')).left)};
};
await page.waitForFunction(()=>[...document.querySelectorAll('.floating-twin .message-actions')].every(e=>getComputedStyle(e).opacity==='0'));
const initial=await page.evaluate(measure);
check('发送消息右对齐',initial.rightAligned,initial);
check('消息之间至少20px',initial.gaps.every(g=>g>=19.5),initial.gaps);
check('默认隐藏回复操作',initial.opacities.length>0&&initial.opacities.every(v=>v==='0'),initial.opacities);
check('移除三项快捷提问',initial.suggestions===0,initial.suggestions);
check('提示文字13px',initial.placeholder==='13px',initial.placeholder);
check('复制图标与回复正文左对齐',initial.copyAlignment.every(x=>Math.abs(x)<1),initial.copyAlignment);
await page.screenshot({path:out+'/desktop.png'});
const lastId=await page.evaluate(()=>[...document.querySelectorAll('.floating-body .assistant-row[data-message-id]')].at(-1).dataset.messageId);
const target=`.floating-body [data-message-id="${lastId}"]`;
await page.hover(target);
await page.waitForFunction(()=>getComputedStyle([...document.querySelectorAll('.floating-body .message-actions')].at(-1)).opacity==='1');
check('仅悬停对应回复显示操作',await page.evaluate(()=>{const a=[...document.querySelectorAll('.floating-body .message-actions')];return a.at(-1)&&getComputedStyle(a.at(-1)).opacity==='1'&&a.slice(0,-1).every(e=>getComputedStyle(e).opacity==='0')}));
await page.screenshot({path:out+'/desktop-hover.png'});
await page.hover('.floating-header');
await page.focus(target+' .message-action:first-child');
await page.waitForFunction(()=>getComputedStyle([...document.querySelectorAll('.floating-body .message-actions')].at(-1)).opacity==='1');
check('键盘聚焦显示操作',true);
await page.click(target+' .message-action:first-child');
await page.waitForFunction(()=>document.querySelector('.floating-body .message-copy-status:last-child')!==null&&[...document.querySelectorAll('.floating-body .message-copy-status')].some(e=>e.textContent==='已复制'));
check('复制回复成功状态',true);
await page.reload();await page.click('.twin-entry');
check('刷新后布局保持',await page.evaluate(()=>document.querySelector('.floating-body>.conversation')!==null&&!document.querySelector('.float-suggestions')));
await page.cdp('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
await page.cdp('Emulation.setTouchEmulationEnabled',{enabled:true});
await page.reload();await page.click('.mobile-bar button[aria-label="询问你的分身"]');
const mobile=await page.evaluate(measure);
check('窄屏右对齐且无横向溢出',mobile.rightAligned&&!mobile.overflow,mobile);
check('窄屏输入16px提示13px',mobile.input==='16px'&&mobile.placeholder==='13px',mobile);
await page.screenshot({path:out+'/mobile.png'});
await fs.writeFile(out+'/checks.json',JSON.stringify({url:'http://127.0.0.1:46100/chat',checks},null,2));
await page.cdp('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});await page.cdp('Emulation.setTouchEmulationEnabled',{enabled:false});
console.log(JSON.stringify(checks,null,2));
