// Run against memory-library-fixture.mjs. Provide the ego-browser spaceId and an absolute outputDir.
const fs=await import('node:fs/promises');
const page=(await taskSpace(spaceId)).page('p1');
const url='http://127.0.0.1:46870/',checks=[];
const all={soul:true,memory:true,automatic:true,people:true};
const control=async v=>{const r=await fetch(url+'__memory/control',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(v)});if(!r.ok)throw Error('Fixture control failed');};
const check=(name,ok)=>{checks.push({name,ok:!!ok});if(!ok)throw Error(name);};
const clickTab=label=>page.click(`xpath=//button[normalize-space(.)="${label}"]`,{label:`打开${label}标签`});
const memory='[data-memory-view="home"]';
const screenshot=name=>page.screenshot({path:outputDir+'/'+name+'.png'});
await fs.mkdir(outputDir,{recursive:true});
try{
 await control({holds:all});
 await page.goto(url);
 if(!await page.evaluate(()=>!!document.querySelector('[data-memory-page]')))await clickTab('记忆');
 await page.waitForSelector(memory);
 await page.waitForFunction(()=>document.querySelector('[data-memory-page]')?.dataset.memoryRefreshing==='true');
 const overview=await page.evaluate(()=>!!document.querySelector('.mem-folder-grid')&&document.querySelectorAll('[data-memory-loading]').length===0);
 await screenshot(overview?'01-navigation-while-loading':'00-blocked-baseline');
 check('四项读取都挂起时总览入口仍可用',overview);
 check('手写文档未到时新建按钮禁用',await page.evaluate(()=>document.querySelector('.mem-add')?.disabled));
 await page.click('[data-memory-folder="people"]',{label:'打开人物档案'});
 await page.waitForSelector('[data-memory-loading="people"]');
 check('人物页只等待人物档案',await page.evaluate(()=>document.querySelectorAll('[data-memory-loading]').length===1));
 await page.click('.mem-breadcrumb',{label:'返回记忆总览'});
 await clickTab('任务');await clickTab('记忆');await page.waitForSelector(memory);
 check('读请求未结束时仍可切标签',await page.evaluate(()=>!!document.querySelector('.mem-folder-grid')));
 await control({holds:{soul:false,memory:false,automatic:false,people:false},release:true});
 await page.waitForFunction(()=>!document.querySelector('.mem-add')?.disabled&&document.querySelector('[data-memory-folder="category:work"]')?.textContent.includes('产品规划'));
 await screenshot('02-loaded-memory');
 check('返回内容后显示真实资料并允许新建',true);
 await control({failures:{people:503}});
 await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
 await page.waitForSelector('[data-memory-error="people"]');
 check('人物读取失败保留笔记和分类入口',await page.evaluate(()=>document.querySelector('[data-memory-folder="category:work"]')?.textContent.includes('产品规划')));
 await control({failures:{people:0}});
 await page.click('[data-memory-error="people"] button',{label:'重试读取人物档案'});
 await page.waitForFunction(()=>!document.querySelector('[data-memory-error="people"]'));
 await page.click('[data-memory-folder="people"]',{label:'打开已加载的人物档案'});
 await page.waitForSelector('.mem-person-row');
 check('可重试后回到真实档案',await page.evaluate(()=>document.querySelectorAll('.mem-person-row').length===3));
 await screenshot('03-people-recovered');
 await page.click('.mem-breadcrumb',{label:'返回记忆总览'});
 await page.click('[data-memory-folder="category:work"]',{label:'打开工作与项目'});
 await page.click('.mem-category-note',{label:'打开手写笔记'});
 await page.click('[data-memory-page] .cm-row',{label:'编辑手写笔记'});
 const draft='## 工作\n- 原样保留我正在编辑的草稿。';
 await control({document:'## 工作\n- 服务端的新版本。',holds:{people:true}});
 await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
 await page.fill('[data-memory-page] textarea',draft);
 await page.waitForSelector('css=[data-memory-page] button:text-is("重新载入")');
 await page.click('css=[data-memory-page] button:text-is("重新载入")',{label:'重新载入原笔记版本'});
 await page.waitForFunction(()=>!document.querySelector('[data-memory-page] button')?.disabled&&![...document.querySelectorAll('[data-memory-page] button')].some(b=>b.textContent==='重新载入'),undefined,{timeout:3000});
 check('重新载入只等待正在编辑的文档并保留草稿',await page.evaluate(text=>document.querySelector('[data-memory-page] textarea')?.value===text,draft));
}finally{
 await control({holds:{soul:false,memory:false,automatic:false,people:false},failures:{people:0},release:true});
 await fs.writeFile(outputDir+'/browser-checks.json',JSON.stringify({url,checks},null,2));
 console.log({url,passed:checks.filter(c=>c.ok).length,total:checks.length});
}
