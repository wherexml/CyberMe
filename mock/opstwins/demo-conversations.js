export function hydrateDemoConversations(state) {
  for(const session of state.sessions){
    const preset=demoSessions.find(x=>x.id===session.id);if(!preset)continue;
    const messages=session.messages;
    const defaultMain=session.id==='main'&&messages[0]?.role==='user'&&messages[0].text===preset.messages[0].text&&messages[1]?.role==='assistant'&&messages[1].text===legacyMain;
    const defaultReview=session.id==='review'&&messages[0]?.role==='assistant'&&messages[0].text===legacyReview;
    const emptyResearch=session.id==='research'&&messages.length===0;
    if(defaultMain||defaultReview||emptyResearch){
      const count=defaultMain?2:defaultReview?1:0;
      if(messages.length>count){
        // Expand the old authored answer without inserting fake user turns ahead of real follow-ups.
        const index=defaultMain?1:0;
        session.messages=messages.map((m,i)=>i===index?{...m,text:defaultMain?overview:agenda}:m);
      }else session.messages=structuredClone(preset.messages);
    }
    session.messages=session.messages.map((m,i)=>m.role==='assistant'&&!m.requestId&&m.text===legacyReply&&session.messages[i-1]?.role==='user'?{...m,text:demoReply(session,session.messages[i-1].text)}:m);
  }
}

export function demoReply(session,text) {
  // Select authored read-only follow-ups; this never dispatches business actions.
  if(/风险|异常|失败|超时|覆盖|保护/.test(text))return risks;
  if(/回复|林可|周宁|怎么说/.test(text))return replies;
  if(/清单|验收|检查/.test(text))return checklist;
  if(/下一步|行动|任务|推进/.test(text))return nextSteps;
  if(/自动|权限|确认边界/.test(text))return boundaries;
  if(/工作流|收件箱|来源/.test(text))return workflow;
  if(/评审|范围|议程|安排/.test(text))return agenda;
  return session.id==='review'?checklist:session.id==='research'?workflow:nextSteps;
}

